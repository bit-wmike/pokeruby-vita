#!/usr/bin/env python3
"""Generates the port's definitions of the RAM symbols that the GBA build
only defines in its linker scripts (sym_ewram.txt / sym_bss.txt: `name = .;`).

On the host the GBA memory regions are arrays (gHostEwram / gHostIwram); each
symbol is placed at the same offset it has on the GBA, so overlapping regions
(gSharedMem and friends) keep working. Addresses come from the GBA build's
map file.

usage: gen_mem.py <build/<name>/sym_ewram.ld> <sym_bss.ld> <poke*.map> <out.s>
"""
import re
import sys

def linker_assigned(path):
    names = []
    for line in open(path):
        m = re.match(r'\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*\.\s*;', line)
        if m:
            names.append(m.group(1))
    return names

def map_addresses(path):
    addr = {}
    for line in open(path):
        m = re.match(r'\s+0x([0-9a-fA-F]{8,16})\s+([A-Za-z_][A-Za-z0-9_]*)\s*(=\s*\.)?\s*$', line)
        if m:
            addr.setdefault(m.group(2), int(m.group(1), 16))
    return addr

def main():
    ewram_ld, bss_ld, mapfile, out = sys.argv[1:5]
    addr = map_addresses(mapfile)
    names = linker_assigned(ewram_ld) + linker_assigned(bss_ld)
    # The arrays are defined here so that the symbols can be equated to
    # offsets inside them.
    lines = ["/* Generated by tools/port/gen_mem.py - do not edit. */",
             "\t.section .bss",
             "\t.p2align 6",
             "\t.globl gHostEwram\ngHostEwram:\n\t.space 0x40000",
             "\t.p2align 6",
             "\t.globl gHostIwram\ngHostIwram:\n\t.space 0x8000",
             "\t.globl gSharedMem\n\t.set gSharedMem, gHostEwram + 0x0"]
    for n in names:
        if n not in addr:
            sys.exit("gen_mem: no address for %s" % n)
        a = addr[n]
        if 0x02000000 <= a < 0x02040000:
            base, off = "gHostEwram", a - 0x02000000
        elif 0x03000000 <= a < 0x03008000:
            base, off = "gHostIwram", a - 0x03000000
        else:
            sys.exit("gen_mem: %s at %#x is not in RAM" % (n, a))
        lines.append("\t.globl %s\n\t.set %s, %s + 0x%x" % (n, n, base, off))
    # Constants the linker script defines (their address is the value).
    for line in open(mapfile):
        m = re.match(r'\s+0x[0-9a-fA-F]+\s+(gNumMusicPlayers|gMaxLines)\s*=\s*(0x[0-9a-fA-F]+|\d+)\s*$', line)
        if m:
            lines.append("\t.globl %s\n\t.set %s, %s" % (m.group(1), m.group(1), m.group(2)))
    open(out, "w").write("\n".join(lines) + "\n")

main()
